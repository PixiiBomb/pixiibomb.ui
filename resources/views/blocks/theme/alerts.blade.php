    <h1>Alerts</h1>

    <p class="lead">
        Create Bootstrap-compatible alerts using regular HTML or the
        PixiiBomb Alert Block API.
    </p>
</div>

<x-pixii::doc-section
    title="Using HTML"
    description="PixiiBomb UI builds on Bootstrap, so standard Bootstrap alert markup works normally.">
    <p>
        Buttons begin with Bootstrap's
        <code>alert</code>
        class and a style class such as
        <code>alert-primary</code>.
        You do not need to use the PixiiBomb Block API to use PixiiBomb's
        alert styles.
    </p>

    <x-pixii::code-example language="html">
        <x-slot:preview>
            <div class="alert alert-info">
                You did it!
            </div>
        </x-slot:preview>

        <x-slot:source>
            <button type="button" class="btn btn-primary">
                Primary
            </button>
        </x-slot:source>
    </x-pixii::code-example>

    <p>
        PixiiBomb extends Bootstrap with additional styles and variants.
        The examples below display the HTML generated by each Button Block,
        allowing you to use the same class combinations directly in HTML.
    </p>
</x-pixii::doc-section>
