<x-pixii::doc-section
    title="Using HTML"
    description="PixiiBomb UI builds on Bootstrap, so standard Bootstrap button markup works normally.">
    <p>
        Buttons begin with Bootstrap's
        <code>btn</code>
        class and a style class such as
        <code>btn-primary</code>.
        You do not need to use the PixiiBomb Block API to use PixiiBomb's
        button styles.
    </p>

    <x-pixii::code-example language="html">
        <x-slot:preview>
            <button type="button" class="btn btn-primary">
                Primary
            </button>
        </x-slot:preview>

        <x-slot:source>
            <button type="button" class="btn btn-primary">
                Primary
            </button>
        </x-slot:source>
    </x-pixii::code-example>

    <p>
        PixiiBomb extends Bootstrap with additional styles and variants.
        The examples below display the HTML generated by each Button Block,
        allowing you to use the same class combinations directly in HTML.
    </p>
</x-pixii::doc-section>

<x-pixii::doc-section
    title="Using the Block API"
    description="Button Blocks provide a fluent PHP API for constructing buttons in controllers, services, or Blade views.">
    <p>
        Create a Button by passing its visible text to the constructor.
        A new Button uses the primary style and solid variant by default.
    </p>

    <x-pixii::code-example language="php" label="PixiiBomb Block">
        <x-slot:preview>
            @block($primaryButton)
        </x-slot:preview>

        <x-slot:source>
            @verbatim
                use PixiiBomb\Ui\Blocks\Button;

                $button = new Button('Primary');
            @endverbatim
        </x-slot:source>
    </x-pixii::code-example>

    <p>
        Render the Button from a Blade view using the
        <code>@@block</code>
        directive:
    </p>

    <x-pixii::code-example language="blade" label="Blade">
        <x-slot:preview>
            @block($primaryButton)
        </x-slot:preview>

        <x-slot:source>
            @verbatim
                @block($button)
            @endverbatim
        </x-slot:source>
    </x-pixii::code-example>
</x-pixii::doc-section>

<x-pixii::doc-section
    title="Styles and Variants"
    description="Use the fluent Button API to select a semantic style and visual variant.">
    <p>
        The button style controls its semantic color, while the variant
        controls how that color is presented.
    </p>

    <x-pixii::code-example
        language="php"
        label="PixiiBomb Block">
        <x-slot:preview>
            @block($configuredButton)
        </x-slot:preview>

        <x-slot:source>
            @verbatim
                use PixiiBomb\Ui\Blocks\Button;
                use PixiiBomb\Ui\Enums\ButtonStyle;
                use PixiiBomb\Ui\Enums\ButtonVariant;

                $button = (new Button('Primary Outline'))
                ->setStyle(ButtonStyle::PRIMARY)
                ->setVariant(ButtonVariant::OUTLINE);
            @endverbatim
        </x-slot:source>
    </x-pixii::code-example>

    <p>
        Both methods accept their corresponding backed enum values, helping
        prevent unsupported class combinations from being assigned to a
        Button.
    </p>
</x-pixii::doc-section>

