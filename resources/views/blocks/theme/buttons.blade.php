@php
    use PixiiBomb\Ui\Blocks\Button;
    use PixiiBomb\Ui\Enums\{ButtonStyle, ButtonVariant};
    use PixiiBomb\Ui\Support\PixiiThemeUtilities as Utils;

    $primaryButton = new Button('Primary');

    $configuredButton = (new Button('Primary Outline'))
        ->setStyle(ButtonStyle::PRIMARY)
        ->setVariant(ButtonVariant::OUTLINE);

    $disabledButton = (new Button('Disabled'))
        ->setDisabled();

    $customAttributeButton = (new Button('Custom Attributes'))
        ->setAttribute('aria-label', 'Example button')
        ->setAttribute('data-example', 'custom-attributes')
        ->addClass('custom-button-class');

    $buttonsSolid = Utils::getButtonGroup(ButtonVariant::SOLID);
    $buttonsOutline = Utils::getButtonGroup(ButtonVariant::OUTLINE);
    $buttonsLink = Utils::getButtonGroup(ButtonVariant::LINK);
@endphp

